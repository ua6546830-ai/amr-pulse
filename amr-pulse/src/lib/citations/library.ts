export const CITATION_MAP = new Map(CITATIONS.map((c) => [c.id, c]));

export function isVerifiedCitationId(id: string): boolean {
  return CITATION_MAP.has(id);
}

export function citationLabel(id: string): string {
  const c = CITATION_MAP.get(id);
  return c ? `${c.authors.split(",")[0]} ${c.year}` : id;
}
